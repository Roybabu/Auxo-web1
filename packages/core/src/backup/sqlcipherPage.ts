import aesjs from "aes-js";
import { bs } from "./webCryptoCompat";

/**
 * Decrypts a SQLCipher-4-format `auxo.db` file (as produced by `net.zetetic:sqlcipher-android`,
 * the library the Android app uses) into a plain, standard SQLite file byte-for-byte in place —
 * same length, same page layout, just with each page's content decrypted and the magic header
 * bytes restored. Any ordinary SQLite engine (e.g. a WASM build) can then open the result.
 *
 * Built directly from SQLCipher's own C source (`sqlcipher/sqlcipher`, `src/sqlcipher.c` and
 * `src/crypto_openssl.c` — see docs/backup-format.md for citations), not approximated, and
 * verified against a real SQLCipher-4-compatible file generated by `tools/android-backup-vectors`.
 *
 * Per-page layout (page_sz bytes, reserve_sz = iv_sz + hmac_sz at the tail of every page):
 * - Page 1 only: first 16 bytes are the KDF salt (stored unencrypted; the *decrypted* view
 *   replaces them with the literal "SQLite format 3\0" magic — SQLCipher does this exact
 *   substitution, not a decryption).
 * - Ciphertext content: AES-256-CBC, no padding (SQLCipher never pads; the content is already
 *   block-aligned).
 * - IV: 16 random bytes, stored in the clear immediately after the ciphertext content.
 * - HMAC-SHA512 (full 64-byte digest, not truncated): covers ciphertext || IV || pgno
 *   (4-byte little-endian), keyed with a key derived from the *encryption* key (not the
 *   passphrase) via a fast (2-iteration) PBKDF2 pass with the KDF salt XORed with 0x3a.
 */

export const SQLCIPHER4_PAGE_SIZE = 4096;
const FILE_HEADER_SIZE = 16; // salt size on page 1; also PBKDF2 salt length
const IV_SIZE = 16;
const HMAC_SIZE = 64; // full SHA-512 digest, SQLCipher does not truncate
const RESERVE_SIZE = IV_SIZE + HMAC_SIZE; // 80
const KEY_SIZE = 32; // AES-256
const KDF_ITERATIONS = 256_000;
const FAST_KDF_ITERATIONS = 2;
const HMAC_SALT_MASK = 0x3a;
const SQLITE_MAGIC = new TextEncoder().encode("SQLite format 3\0");

export class WrongDatabaseKeyError extends Error {
  constructor(pageNumber: number) {
    super(`SQLCipher HMAC check failed on page ${pageNumber}: wrong key or corrupt database`);
    this.name = "WrongDatabaseKeyError";
  }
}

export function looksLikePlaintextSqlite(fileBytes: Uint8Array): boolean {
  if (fileBytes.length < SQLITE_MAGIC.length) return false;
  for (let i = 0; i < SQLITE_MAGIC.length; i++) {
    if (fileBytes[i] !== SQLITE_MAGIC[i]) return false;
  }
  return true;
}

async function pbkdf2(
  passwordBytes: Uint8Array,
  salt: Uint8Array,
  iterations: number,
  lengthBytes: number,
): Promise<Uint8Array> {
  const key = await crypto.subtle.importKey("raw", bs(passwordBytes), "PBKDF2", false, ["deriveBits"]);
  const bits = await crypto.subtle.deriveBits(
    { name: "PBKDF2", hash: "SHA-512", salt: bs(salt), iterations },
    key,
    lengthBytes * 8,
  );
  return new Uint8Array(bits);
}

async function hmacSha512(key: Uint8Array, data: Uint8Array): Promise<Uint8Array> {
  const cryptoKey = await crypto.subtle.importKey(
    "raw",
    bs(key),
    { name: "HMAC", hash: "SHA-512" },
    false,
    ["sign"],
  );
  const signature = await crypto.subtle.sign("HMAC", cryptoKey, bs(data));
  return new Uint8Array(signature);
}

function concat(...parts: Uint8Array[]): Uint8Array {
  const total = parts.reduce((sum, p) => sum + p.length, 0);
  const result = new Uint8Array(total);
  let pos = 0;
  for (const part of parts) {
    result.set(part, pos);
    pos += part.length;
  }
  return result;
}

function pgnoLittleEndian(pgno: number): Uint8Array {
  const bytes = new Uint8Array(4);
  new DataView(bytes.buffer).setUint32(0, pgno, true);
  return bytes;
}

export interface SqlCipherKeys {
  encryptionKey: Uint8Array;
  hmacKey: Uint8Array;
}

/**
 * Derives the AES-256 encryption key and the separate HMAC key from the 64-hex-char
 * `database.key` passphrase and the 16-byte KDF salt (the first 16 bytes of the database file).
 */
export async function deriveSqlCipherKeys(
  databaseKeyPassphrase: string,
  kdfSalt: Uint8Array,
): Promise<SqlCipherKeys> {
  if (kdfSalt.length !== FILE_HEADER_SIZE) {
    throw new Error(`kdfSalt must be ${FILE_HEADER_SIZE} bytes`);
  }
  const passphraseBytes = new TextEncoder().encode(databaseKeyPassphrase);
  const encryptionKey = await pbkdf2(passphraseBytes, kdfSalt, KDF_ITERATIONS, KEY_SIZE);

  const hmacSalt = new Uint8Array(kdfSalt.length);
  for (let i = 0; i < kdfSalt.length; i++) {
    hmacSalt[i] = kdfSalt[i]! ^ HMAC_SALT_MASK;
  }
  const hmacKey = await pbkdf2(encryptionKey, hmacSalt, FAST_KDF_ITERATIONS, KEY_SIZE);

  return { encryptionKey, hmacKey };
}

/** Raw AES-256-CBC decryption with no padding handling (SQLCipher pages are never padded). */
function aesCbcDecryptNoPadding(key: Uint8Array, iv: Uint8Array, ciphertext: Uint8Array): Uint8Array {
  const cbc = new aesjs.ModeOfOperation.cbc(key, iv);
  return cbc.decrypt(ciphertext);
}

function aesCbcEncryptNoPadding(key: Uint8Array, iv: Uint8Array, plaintext: Uint8Array): Uint8Array {
  const cbc = new aesjs.ModeOfOperation.cbc(key, iv);
  return cbc.encrypt(plaintext);
}

/**
 * Decrypts a full SQLCipher-4 database file into a plain SQLite file, verifying every page's
 * HMAC. Throws `WrongDatabaseKeyError` identifying the first page that fails to authenticate.
 */
export async function decryptSqlCipherDatabase(
  databaseKeyPassphrase: string,
  fileBytes: Uint8Array,
  pageSize: number = SQLCIPHER4_PAGE_SIZE,
): Promise<Uint8Array> {
  if (looksLikePlaintextSqlite(fileBytes)) {
    // Already a plain database (e.g. SQLCipher failed to load on the source device) — nothing to do.
    return fileBytes.slice();
  }
  if (fileBytes.length % pageSize !== 0 || fileBytes.length === 0) {
    throw new Error(`Database file length ${fileBytes.length} is not a multiple of page size ${pageSize}`);
  }

  const kdfSalt = fileBytes.slice(0, FILE_HEADER_SIZE);
  const { encryptionKey, hmacKey } = await deriveSqlCipherKeys(databaseKeyPassphrase, kdfSalt);

  const output = fileBytes.slice();
  const pageCount = fileBytes.length / pageSize;

  for (let pgno = 1; pgno <= pageCount; pgno++) {
    const pageStart = (pgno - 1) * pageSize;
    const headerOffset = pgno === 1 ? FILE_HEADER_SIZE : 0;
    const contentLength = pageSize - headerOffset - RESERVE_SIZE;
    const contentStart = pageStart + headerOffset;
    const ivStart = contentStart + contentLength;
    const hmacStart = ivStart + IV_SIZE;

    const ciphertext = fileBytes.subarray(contentStart, ivStart);
    const iv = fileBytes.subarray(ivStart, ivStart + IV_SIZE);
    const storedHmac = fileBytes.subarray(hmacStart, hmacStart + HMAC_SIZE);

    const computedHmac = await hmacSha512(hmacKey, concat(ciphertext, iv, pgnoLittleEndian(pgno)));
    if (!timingSafeEqual(computedHmac, storedHmac)) {
      throw new WrongDatabaseKeyError(pgno);
    }

    const plaintext = aesCbcDecryptNoPadding(encryptionKey, iv, ciphertext);
    output.set(plaintext, contentStart);
    if (pgno === 1) {
      output.set(SQLITE_MAGIC, pageStart);
    }
  }

  return output;
}

/**
 * Encrypts a plain SQLite file byte array (must already be laid out with `pageSize` pages and
 * `RESERVE_SIZE` reserved bytes per page, i.e. produced with `PRAGMA page_size` and
 * `cipher_reserve` matching SQLCipher 4) into SQLCipher-4 format using the given passphrase.
 * A fresh random KDF salt and per-page IVs are generated.
 */
export async function encryptSqlCipherDatabase(
  databaseKeyPassphrase: string,
  plainFileBytes: Uint8Array,
  pageSize: number = SQLCIPHER4_PAGE_SIZE,
): Promise<Uint8Array> {
  if (plainFileBytes.length % pageSize !== 0 || plainFileBytes.length === 0) {
    throw new Error(`Database file length ${plainFileBytes.length} is not a multiple of page size ${pageSize}`);
  }
  const kdfSalt = crypto.getRandomValues(new Uint8Array(FILE_HEADER_SIZE));
  const { encryptionKey, hmacKey } = await deriveSqlCipherKeys(databaseKeyPassphrase, kdfSalt);

  const output = plainFileBytes.slice();
  const pageCount = plainFileBytes.length / pageSize;

  for (let pgno = 1; pgno <= pageCount; pgno++) {
    const pageStart = (pgno - 1) * pageSize;
    const headerOffset = pgno === 1 ? FILE_HEADER_SIZE : 0;
    const contentLength = pageSize - headerOffset - RESERVE_SIZE;
    const contentStart = pageStart + headerOffset;
    const ivStart = contentStart + contentLength;
    const hmacStart = ivStart + IV_SIZE;

    const iv = crypto.getRandomValues(new Uint8Array(IV_SIZE));
    const plaintext = plainFileBytes.subarray(contentStart, ivStart);
    const ciphertext = aesCbcEncryptNoPadding(encryptionKey, iv, plaintext);

    output.set(ciphertext, contentStart);
    output.set(iv, ivStart);

    const hmac = await hmacSha512(hmacKey, concat(ciphertext, iv, pgnoLittleEndian(pgno)));
    output.set(hmac, hmacStart);

    if (pgno === 1) {
      output.set(kdfSalt, pageStart);
    }
  }

  return output;
}

function timingSafeEqual(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) {
    diff |= a[i]! ^ b[i]!;
  }
  return diff === 0;
}
